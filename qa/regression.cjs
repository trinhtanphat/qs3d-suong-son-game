'use strict';
const {chromium}=require('playwright-core');
const fs=require('node:fs'),path=require('node:path');
const out=process.env.QA_OUT_DIR||path.join(__dirname,'..','qa-out');
fs.mkdirSync(out,{recursive:true});
const target=process.env.GAME_URL||'http://127.0.0.1:5402/';
const cdp=process.env.CDP_URL||'http://127.0.0.1:9222';
const report={url:target,at:new Date().toISOString(),checks:[],pageErrors:[],httpErrors:[]};
function check(name, condition, details){
 report.checks.push({name,passed:!!condition,details:details===undefined?'':details});
 if(!condition)throw Error('FAILED: '+name+'; '+JSON.stringify(details));
}
const nap=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
 const browser=await chromium.connectOverCDP(cdp,{timeout:30000});
 const context=await browser.newContext({viewport:{width:1366,height:768},acceptDownloads:false,serviceWorkers:'block'});
 const page=await context.newPage();
 const capture=p=>{
  p.on('pageerror',e=>report.pageErrors.push(String(e)));
  p.on('console',m=>{if(m.type()==='error')report.pageErrors.push(m.text())});
  p.on('response',r=>{if(r.status()>=400)report.httpErrors.push(r.status()+' '+r.url())});
 };
 capture(page);
 const snap=()=>page.evaluate(()=>window.__qs3dGame.snapshot());
 try{
  const res=await page.goto(target,{waitUntil:'domcontentloaded',timeout:35000});
  check('desktop page HTTP200',res.status()===200,res.status());
  await page.waitForFunction(()=>document.documentElement.dataset.ready==='true',null,{timeout:35000});
  const s0=await snap();
  check('init WebGL2',s0.webgl2===true);
  check('initial intro only',s0.mode==='intro'&&s0.wave===0);
  await page.keyboard.press('j');
  check('attack ignored before starting', (await snap()).attacks===0);
  check('independent game disclosure',await page.locator('.legal').innerText().then(t=>t.includes('Không sao chép tài nguyên')));
  await page.click('#play');
  let s=await snap();
  check('wave 1 has 3 enemies',s.mode==='playing'&&s.wave===1&&s.enemies===3,s);
  check('full starting health',s.health===100);
  check('full starting stamina',s.stamina===100);
  const z=s.z;
  await page.keyboard.down('w'); await page.waitForTimeout(900); await page.keyboard.up('w');
  s=await snap();
  check('W changes Z position',s.z<z-1,{z,after:s.z});
  const x=s.x;
  await page.keyboard.down('d'); await page.waitForTimeout(650); await page.keyboard.up('d');
  s=await snap();
  check('D changes X position',s.x>x+.5,{x,after:s.x});
  await page.keyboard.press('j');
  s=await snap();
  check('keyboard J attacks',s.attacks===1);
  await page.keyboard.press('j');
  check('attack cooldown rejects spamming',(await snap()).attacks===1);
  await page.waitForTimeout(560);await page.mouse.click(650,420);
  check('mouse left attacks after cooldown',(await snap()).attacks===2);
  await page.keyboard.down('k');
  check('K engages guard',(await snap()).blocking===true);
  await page.keyboard.up('k');
  check('K release disengages guard',(await snap()).blocking===false);
  const beforeQ=(await snap()).mana;
  await page.keyboard.press('q');const afterQ=(await snap()).mana;
  check('Q consumes 22 mana',afterQ<=beforeQ-21,{beforeQ,afterQ});
  await page.keyboard.press('q');
  check('skill cooldown blocks immediate second Q',(await snap()).mana>=afterQ-1);
  await page.keyboard.press(' ');
  s=await snap();check('space dodge increments and invulnerable',s.dodges===1&&s.invulnerable,s);
  await page.keyboard.press(' ');
  check('dodge cooldown rejects second press',(await snap()).dodges===1);
  await page.evaluate(()=>window.__qs3dGame.start());
  s=await snap();
  check('fresh match resets counters and wave',s.kills===0&&s.attacks===0&&s.wave===1&&s.health===100,s);
  const beforeF=s.mana;
  await page.keyboard.press('f');
  check('heal not wasted at full HP',(await snap()).mana>=beforeF-.6);
  await page.keyboard.press('e');
  s=await snap();
  check('ultimate spends 65 mana accounting for 12-per-kill refunds',beforeF-s.mana+12*s.kills>=64&&beforeF-s.mana+12*s.kills<67,{start:beforeF,after:s.mana,kills:s.kills});
  check('ultimate gives invulnerability',s.invulnerable===true);
  await page.keyboard.press('e');
  check('ultimate cannot be re-spammed',(await snap()).mana>=s.mana-.5);
  await page.evaluate(()=>window.__qs3dGame.start());
  await page.waitForFunction(()=>window.__qs3dGame.snapshot().health<100,null,{timeout:75000,polling:350});
  s=await snap();check('enemy attacks can reduce HP',s.health<100&&s.hits>0,s);
  const beforeHeal={hp:s.health,mana:s.mana};
  await page.keyboard.press('f');s=await snap();
  check('F heals player',s.health>beforeHeal.hp&&s.health<=100,{beforeHeal,after:s});
  check('F consumes 30 mana',s.mana<=beforeHeal.mana-29,{beforeHeal,after:s});
  await page.keyboard.down('k');
  await page.waitForFunction(()=>window.__qs3dGame.snapshot().blocks>0,null,{timeout:60000,polling:400});
  s=await snap();check('guard mitigates actual enemy hit',s.blocks>0&&s.blocking===true,s);
  await page.keyboard.up('k');
  check('guard releases without stuck key',(await snap()).blocking===false);
  await page.screenshot({path:path.join(out,'regression-desktop.png')});
  await context.close();

  const mobileCtx=await browser.newContext({viewport:{width:360,height:640},deviceScaleFactor:1,isMobile:true,hasTouch:true,acceptDownloads:false,serviceWorkers:'block'});
  const m=await mobileCtx.newPage();capture(m);
  try{
   await m.goto(target,{waitUntil:'domcontentloaded',timeout:35000});
   await m.waitForFunction(()=>document.documentElement.dataset.ready==='true',null,{timeout:35000});
   const btn=m.locator('#play');
   check('small screen has visible start button',await btn.isVisible());
   const scroll=await m.evaluate(()=>({scrollable:document.querySelector('#intro').scrollHeight>=document.querySelector('#intro').clientHeight,overflow:getComputedStyle(document.querySelector('#intro')).overflowY}));
   check('intro allows vertical scrolling on short screens',scroll.overflow==='auto',scroll);
   await btn.click({timeout:12000});
   check('mobile starts wave1',(await m.evaluate(()=>window.__qs3dGame.snapshot())).wave===1);
   check('touch action UI displayed',await m.locator('.mobile-ui').evaluate(e=>getComputedStyle(e).display==='flex'));
   const tSnap=()=>m.evaluate(()=>window.__qs3dGame.snapshot());
   await m.locator('[data-act="attack"]').tap();
   check('mobile attack button works',(await tSnap()).attacks===1);
   await m.locator('[data-act="dodge"]').tap();
   check('mobile dodge button works',(await tSnap()).dodges===1);
   const qmana=(await tSnap()).mana;
   await m.locator('[data-act="q"]').tap();
   check('mobile Q consumes mana',(await tSnap()).mana<qmana-21);
   await m.evaluate(()=>window.__qs3dGame.start());
   const emana=(await tSnap()).mana;
   await m.locator('[data-act="e"]').tap();
   const mobileUltimate=await tSnap();check('mobile E consumes 65 mana with 12-per-kill refunds',emana-mobileUltimate.mana+12*mobileUltimate.kills>=64&&emana-mobileUltimate.mana+12*mobileUltimate.kills<67,{start:emana,after:mobileUltimate});
   await m.evaluate(()=>window.__qs3dGame.start());
   const zz=(await tSnap()).z;
   await m.locator('[data-act="up"]').dispatchEvent('pointerdown',{pointerId:4,pointerType:'touch',isPrimary:true});
   await m.waitForTimeout(1100);
   await m.locator('[data-act="up"]').dispatchEvent('pointerup',{pointerId:4,pointerType:'touch',isPrimary:true});
   check('mobile directional hold moves hero',(await tSnap()).z<zz-.8,{before:zz,after:(await tSnap()).z});
   await m.screenshot({path:path.join(out,'regression-mobile-360.png')});
  }finally{await mobileCtx.close()}
  check('zero browser exceptions',report.pageErrors.length===0,report.pageErrors);
  check('zero failed HTTP asset responses',report.httpErrors.length===0,report.httpErrors);
 }finally{
  report.total=report.checks.length;report.passed=report.checks.filter(c=>c.passed).length;report.failed=report.total-report.passed;
  fs.writeFileSync(path.join(out,'regression.json'),JSON.stringify(report,null,2));
  try{await context.close()}catch{}
 }
 console.log('REGRESSION_RESULT',JSON.stringify({total:report.total,passed:report.passed,failed:report.failed,errors:report.pageErrors,httpErrors:report.httpErrors,output:out}));
 process.exit(report.failed?1:0);
})().catch(e=>{
 report.error=String(e.stack||e);report.total=report.checks.length;report.passed=report.checks.filter(c=>c.passed).length;report.failed=Math.max(1,report.total-report.passed);
 fs.writeFileSync(path.join(out,'regression.json'),JSON.stringify(report,null,2));
 console.error('REGRESSION_FAILURE',report.error);process.exit(1);
});